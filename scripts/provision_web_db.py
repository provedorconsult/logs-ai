"""Provision isolated web metadata/roles on the dedicated logs-ai PostgreSQL only.

Run in its private database network. Credentials are hexadecimal environment
variables; SQL receives SCRAM verifiers generated by libpq, never plaintext.
"""

import argparse
import os
import re
from urllib.parse import quote, urlsplit, urlunsplit

import psycopg
from psycopg import sql


def provision(grant_registry=False):
    admin = os.environ["WEB_DATABASE_ADMIN_URL"]
    parsed = urlsplit(admin)
    database = parsed.path.removeprefix("/")
    if (
        parsed.scheme != "postgresql"
        or parsed.username != "logs_ai"
        or database not in ("logs_ai", "logs_ai_test")
        or parsed.query
        or parsed.fragment
    ):
        raise ValueError("Use only the dedicated logs-ai database administrator")
    roles = {
        "logs_ai_web": os.environ["WEB_DB_PASSWORD"],
        "logs_ai_web_reader": os.environ["WEB_READER_PASSWORD"],
        "logs_ai_clients_reader": os.environ["WEB_REGISTRY_PASSWORD"],
        "logs_ai_ingest": os.environ["WEB_INGEST_PASSWORD"],
    }
    if any(not re.fullmatch(r"[0-9a-f]{64}", value) for value in roles.values()):
        raise ValueError("Protected credentials must be random hexadecimal values")
    with psycopg.connect(admin, autocommit=True, connect_timeout=5) as conn:
        identity = conn.execute("SELECT current_database(),current_user").fetchone()
        if identity != (database, "logs_ai"):
            raise ValueError("Unexpected PostgreSQL identity")
        for role, password in roles.items():
            exists = conn.execute(
                "SELECT oid,rolsuper,rolcreaterole,rolcreatedb,rolreplication,rolbypassrls "
                "FROM pg_roles WHERE rolname=%s",
                (role,),
            ).fetchone()
            if exists:
                if (
                    any(exists[1:])
                    or conn.execute(
                        "SELECT 1 FROM pg_auth_members WHERE member=%s", (exists[0],)
                    ).fetchone()
                ):
                    raise ValueError("Existing role privileges differ; preserve and inspect")
                # Prove control of an existing role before granting it any new access.
                dsn = (
                    f"postgresql://{role}:{quote(password)}@{parsed.hostname}:"
                    f"{parsed.port or 5432}/{database}"
                )
                with psycopg.connect(dsn, connect_timeout=5) as existing:
                    existing.execute("SELECT 1")
            else:
                verifier = conn.pgconn.encrypt_password(
                    password.encode(), role.encode(), b"scram-sha-256"
                ).decode()
                conn.execute(
                    sql.SQL(
                        "CREATE ROLE {} LOGIN NOSUPERUSER NOCREATEDB NOCREATEROLE "
                        "NOREPLICATION NOBYPASSRLS PASSWORD {}"
                    ).format(sql.Identifier(role), sql.Literal(verifier))
                )
        owner = conn.execute(
            "SELECT pg_get_userbyid(datdba) FROM pg_database WHERE datname='logs_ai_web'"
        ).fetchone()
        if owner and owner[0] != "logs_ai_web":
            raise ValueError("Metadata database has another owner; not reused")
        if not owner:
            conn.execute("CREATE DATABASE logs_ai_web OWNER logs_ai_web")
        conn.execute("REVOKE ALL ON DATABASE logs_ai_web FROM PUBLIC")
        conn.execute("GRANT CONNECT ON DATABASE logs_ai_web TO logs_ai_clients_reader")
        conn.execute(
            sql.SQL("GRANT CONNECT ON DATABASE {} TO logs_ai_web_reader").format(
                sql.Identifier(database)
            )
        )
        conn.execute("GRANT USAGE ON SCHEMA public TO logs_ai_web_reader")
        conn.execute("GRANT SELECT ON log_events TO logs_ai_web_reader")
        conn.execute(
            sql.SQL("GRANT CONNECT ON DATABASE {} TO logs_ai_ingest").format(
                sql.Identifier(database)
            )
        )
        conn.execute("GRANT USAGE ON SCHEMA public TO logs_ai_ingest")
        conn.execute("GRANT INSERT ON log_events TO logs_ai_ingest")
        conn.execute("GRANT USAGE ON SEQUENCE log_events_id_seq TO logs_ai_ingest")
        conn.execute("GRANT SELECT(version,checksum) ON schema_migrations TO logs_ai_ingest")
        for role in ("logs_ai_web_reader", "logs_ai_clients_reader"):
            conn.execute(
                sql.SQL("ALTER ROLE {} SET default_transaction_read_only=on").format(
                    sql.Identifier(role)
                )
            )
    netloc = parsed.netloc
    meta_admin = urlunsplit((parsed.scheme, netloc, "/logs_ai_web", "", ""))
    with psycopg.connect(meta_admin, autocommit=True, connect_timeout=5) as conn:
        conn.execute("REVOKE ALL ON SCHEMA public FROM PUBLIC")
        conn.execute("GRANT USAGE ON SCHEMA public TO logs_ai_clients_reader")
        if grant_registry:
            if not conn.execute("SELECT to_regclass('public.web_client_sources')").fetchone()[0]:
                raise ValueError("Initialize web metadata before registry grant")
            conn.execute("GRANT SELECT ON web_client_sources TO logs_ai_clients_reader")
    # Existing roles are authenticated rather than having their passwords reset.
    for role, password in roles.items():
        target = database if role in ("logs_ai_web_reader", "logs_ai_ingest") else "logs_ai_web"
        port = parsed.port or 5432
        dsn = f"postgresql://{role}:{quote(password)}@{parsed.hostname}:{port}/{target}"
        with psycopg.connect(dsn, connect_timeout=5) as conn:
            conn.execute("SELECT 1")
    return {
        "metadata_database": "logs_ai_web",
        "roles": list(roles),
        "registry_granted": grant_registry,
    }


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--grant-registry", action="store_true")
    args = parser.parse_args()
    try:
        import json

        print(json.dumps(provision(args.grant_registry)))
    except Exception:
        raise SystemExit(
            "Web database provisioning failed; inspect scope/roles without exposing credentials"
        ) from None
